using DotNet.Testcontainers.Builders;
using SkiaSharp;

namespace DietPlanner.E2ETests;

/// <summary>
/// Compares screenshots against baseline PNGs committed under <c>DietPlanner.E2ETests/VisualBaselines/</c>,
/// so visual changes show up as image diffs in the pull request and get approved there like any other
/// change. Playwright's built-in <c>toHaveScreenshot</c> only exists in its Node test runner, hence
/// this small comparer.
///
/// Baselines are only meaningful for the renderer that produced them - fonts and anti-aliasing differ
/// between operating systems - so they're generated by CI's Linux Chromium (see the
/// update-visual-baselines workflow) and comparisons are skipped on other platforms.
/// </summary>
public static class VisualBaseline
{
    /// <summary>Set to <c>true</c> to overwrite baselines with the current rendering instead of comparing.</summary>
    public const string UpdateEnvironmentVariable = "UPDATE_VISUAL_BASELINES";

    // A channel has to move by more than this (out of 255) for a pixel to count as changed, so
    // sub-pixel anti-aliasing noise doesn't fail a run, while a recoloured element still does.
    private const int ChannelTolerance = 32;

    // The fraction of pixels allowed to change before the comparison fails - small enough that a
    // shifted word or a missing border fails, large enough to absorb a stray anti-aliased glyph edge.
    private const double MaxChangedPixelRatio = 0.001;

    public static string BaselineDirectory { get; } = Path.Combine(
        CommonDirectoryPath.GetSolutionDirectory().DirectoryPath, "DietPlanner.E2ETests", "VisualBaselines");

    public static string DiffOutputDirectory { get; } = Path.Combine(
        CommonDirectoryPath.GetSolutionDirectory().DirectoryPath, "DietPlanner.E2ETests", "TestResults", "VisualDiffs");

    private static bool IsUpdating =>
        string.Equals(Environment.GetEnvironmentVariable(UpdateEnvironmentVariable), "true", StringComparison.OrdinalIgnoreCase);

    public static void AssertMatches(string name, byte[] actualPng)
    {
        if (!OperatingSystem.IsLinux())
        {
            Assert.Ignore("Visual baselines are rendered on Linux in CI; comparisons are skipped on other platforms.");
        }

        string baselinePath = Path.Combine(BaselineDirectory, $"{name}.png");

        if (IsUpdating || !File.Exists(baselinePath))
        {
            bool isNew = !File.Exists(baselinePath);
            Directory.CreateDirectory(BaselineDirectory);
            File.WriteAllBytes(baselinePath, actualPng);

            if (isNew && !IsUpdating)
            {
                // Matches Playwright's behaviour: write the missing baseline but still fail, so a new
                // screenshot can't pass CI without someone committing (and a reviewer approving) it.
                WriteDiffArtifact(name, "actual", actualPng);
                Assert.Fail($"No baseline existed for '{name}'; wrote one to {baselinePath}. Review and commit it.");
            }

            return;
        }

        using SKBitmap expected = SKBitmap.Decode(baselinePath);
        using SKBitmap actual = SKBitmap.Decode(actualPng);

        if (expected.Width != actual.Width || expected.Height != actual.Height)
        {
            WriteDiffArtifact(name, "actual", actualPng);
            Assert.Fail(
                $"Screenshot '{name}' is {actual.Width}x{actual.Height} but the baseline is {expected.Width}x{expected.Height}. " +
                $"Actual image written to {DiffOutputDirectory}.");
        }

        using SKBitmap diff = new(actual.Width, actual.Height);
        int changedPixels = 0;

        for (int y = 0; y < actual.Height; y++)
        {
            for (int x = 0; x < actual.Width; x++)
            {
                SKColor e = expected.GetPixel(x, y);
                SKColor a = actual.GetPixel(x, y);

                int delta = Math.Max(
                    Math.Max(Math.Abs(e.Red - a.Red), Math.Abs(e.Green - a.Green)),
                    Math.Max(Math.Abs(e.Blue - a.Blue), Math.Abs(e.Alpha - a.Alpha)));

                if (delta > ChannelTolerance)
                {
                    changedPixels++;
                    diff.SetPixel(x, y, SKColors.Red);
                }
                else
                {
                    // A faded greyscale copy of the page, so the red changed pixels are easy to place.
                    byte grey = (byte)(((a.Red + a.Green + a.Blue) / 3 / 4) + 191);
                    diff.SetPixel(x, y, new SKColor(grey, grey, grey));
                }
            }
        }

        double changedRatio = (double)changedPixels / (actual.Width * actual.Height);
        if (changedRatio > MaxChangedPixelRatio)
        {
            WriteDiffArtifact(name, "expected", File.ReadAllBytes(baselinePath));
            WriteDiffArtifact(name, "actual", actualPng);
            using SKData diffPng = diff.Encode(SKEncodedImageFormat.Png, 100);
            WriteDiffArtifact(name, "diff", diffPng.ToArray());

            Assert.Fail(
                $"Screenshot '{name}' differs from its baseline in {changedPixels} pixels ({changedRatio:P2}). " +
                $"Expected/actual/diff images written to {DiffOutputDirectory}. If the change is intended, " +
                $"regenerate the baselines (see DietPlanner.E2ETests/VisualBaselines/README.md).");
        }
    }

    private static void WriteDiffArtifact(string name, string kind, byte[] png)
    {
        Directory.CreateDirectory(DiffOutputDirectory);
        string path = Path.Combine(DiffOutputDirectory, $"{name}.{kind}.png");
        File.WriteAllBytes(path, png);
        TestContext.AddTestAttachment(path);
    }
}
